import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import world from "@svg-maps/world";
import pathBounds from "svg-path-bounds";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.join(
  scriptDirectory,
  "../src/features/travel/generated-country-bounds.ts",
);

const countries = world.locations
  .filter((location) => location.id.length === 2)
  .map((location) => [location.id.toUpperCase(), pathBounds(location.path)])
  .sort(([left], [right]) => left.localeCompare(right));

if (!countries.length) {
  throw new Error("The world SVG map did not contain two-letter locations.");
}

const body = countries
  .map(
    ([code, bounds]) =>
      `  ${code}: [${bounds.map((value) => Number(value.toFixed(4))).join(", ")}],`,
  )
  .join("\n");

const source = `/* This file is generated by mobile/scripts/generate-map-bounds.mjs. Do not edit by hand. */

export type MapBounds = readonly [
  minX: number,
  minY: number,
  maxX: number,
  maxY: number,
];

export const countryBounds: Readonly<Record<string, MapBounds>> = {
${body}
};
`;

await writeFile(outputPath, source, "utf8");
console.log(`Generated ${countries.length} country bounds at ${outputPath}`);
