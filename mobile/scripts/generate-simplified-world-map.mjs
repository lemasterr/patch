import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import worldModule from "@svg-maps/world";

const world = worldModule.default ?? worldModule;
const tolerance = 0.35;
const catalogUrl = new URL(
  "../src/features/travel/country-catalog.ts",
  import.meta.url,
);
const outputUrl = new URL(
  "../src/features/travel/generated-world-map.ts",
  import.meta.url,
);

function squaredSegmentDistance(point, start, end) {
  const dx = end[0] - start[0];
  const dy = end[1] - start[1];
  if (dx === 0 && dy === 0) {
    return (point[0] - start[0]) ** 2 + (point[1] - start[1]) ** 2;
  }
  const projection = Math.max(
    0,
    Math.min(
      1,
      ((point[0] - start[0]) * dx + (point[1] - start[1]) * dy) /
        (dx * dx + dy * dy),
    ),
  );
  const projectedX = start[0] + dx * projection;
  const projectedY = start[1] + dy * projection;
  return (point[0] - projectedX) ** 2 + (point[1] - projectedY) ** 2;
}

function simplifyOpen(points) {
  if (points.length <= 2) return points;
  const keep = new Uint8Array(points.length);
  const stack = [[0, points.length - 1]];
  const toleranceSquared = tolerance * tolerance;
  keep[0] = 1;
  keep[points.length - 1] = 1;

  while (stack.length) {
    const [startIndex, endIndex] = stack.pop();
    let farthestIndex = -1;
    let farthestDistance = toleranceSquared;
    for (let index = startIndex + 1; index < endIndex; index += 1) {
      const distance = squaredSegmentDistance(
        points[index],
        points[startIndex],
        points[endIndex],
      );
      if (distance > farthestDistance) {
        farthestDistance = distance;
        farthestIndex = index;
      }
    }
    if (farthestIndex >= 0) {
      keep[farthestIndex] = 1;
      stack.push([startIndex, farthestIndex], [farthestIndex, endIndex]);
    }
  }

  return points.filter((_, index) => keep[index]);
}

function simplifyClosed(points) {
  if (points.length <= 4) return points;
  let splitIndex = 1;
  let farthestDistance = -1;
  for (let index = 1; index < points.length; index += 1) {
    const distance =
      (points[index][0] - points[0][0]) ** 2 +
      (points[index][1] - points[0][1]) ** 2;
    if (distance > farthestDistance) {
      farthestDistance = distance;
      splitIndex = index;
    }
  }
  const firstArc = simplifyOpen(points.slice(0, splitIndex + 1));
  const secondArc = simplifyOpen([...points.slice(splitIndex), points[0]]);
  const simplified = [...firstArc.slice(0, -1), ...secondArc.slice(0, -1)];
  return simplified.length >= 3 ? simplified : points.slice(0, 3);
}

function parseRelativePolygons(path) {
  const tokens = path.match(/[mz]|[-+]?(?:\d*\.?\d+)(?:e[-+]?\d+)?/gi) ?? [];
  const polygons = [];
  let index = 0;
  let currentX = 0;
  let currentY = 0;
  let startX = 0;
  let startY = 0;

  while (index < tokens.length) {
    const command = tokens[index++].toLowerCase();
    if (command === "z") {
      currentX = startX;
      currentY = startY;
      continue;
    }
    if (command !== "m") throw new Error(`Unexpected path command ${command}`);
    currentX += Number(tokens[index++]);
    currentY += Number(tokens[index++]);
    startX = currentX;
    startY = currentY;
    const points = [[currentX, currentY]];
    while (index < tokens.length && !/^[mz]$/i.test(tokens[index])) {
      currentX += Number(tokens[index++]);
      currentY += Number(tokens[index++]);
      points.push([currentX, currentY]);
    }
    polygons.push(points);
  }
  return polygons;
}

function formatCoordinate(value) {
  return Number(value.toFixed(2)).toString();
}

function simplifyPath(path) {
  return parseRelativePolygons(path)
    .map((points) => {
      const simplified = simplifyClosed(points);
      return `M${simplified
        .map(([x, y]) => `${formatCoordinate(x)},${formatCoordinate(y)}`)
        .join(" ")}Z`;
    })
    .join("");
}

const catalogSource = await readFile(catalogUrl, "utf8");
const canonicalBlock = catalogSource.match(
  /export const countableCountryCodes = new Set\(\s*\[([\s\S]*?)\]\s*\.join/,
)?.[1];
if (!canonicalBlock) throw new Error("Could not read canonical country codes.");
const countryCodes = new Set(
  [...canonicalBlock.matchAll(/"([A-Z ]+)"/g)]
    .flatMap((match) => match[1].split(" "))
    .filter(Boolean),
);

const locations = world.locations
  .filter(
    (location) =>
      location.id.length === 2 && countryCodes.has(location.id.toUpperCase()),
  )
  .map((location) => ({
    id: location.id,
    name: location.name,
    path: simplifyPath(location.path),
  }));

if (locations.length !== countryCodes.size) {
  throw new Error(
    `Generated ${locations.length} countries for ${countryCodes.size} canonical codes.`,
  );
}

const output =
  `/* This file is generated by scripts/generate-simplified-world-map.mjs. */\n` +
  `/* Paths use absolute coordinates so multiple countries can be safely batched. */\n` +
  `export const simplifiedWorldLocations = ${JSON.stringify(locations)} as const;\n`;
await writeFile(outputUrl, output);

const originalCharacters = world.locations
  .filter((location) => countryCodes.has(location.id.toUpperCase()))
  .reduce((total, location) => total + location.path.length, 0);
const generatedCharacters = locations.reduce(
  (total, location) => total + location.path.length,
  0,
);
console.log(
  `Generated ${locations.length} countries at ${fileURLToPath(outputUrl)} (${originalCharacters} -> ${generatedCharacters} path characters).`,
);
